/**
 * Create a formatted Google Doc for a GST Tax Invoice
 */
export async function createInvoiceGoogleDoc(
  accessToken: string,
  invoice: Invoice,
  business: Business
): Promise<WorkspaceExportResult> {
  try {
    const docTitle = `Tax Invoice - ${invoice.invoiceNumber || 'Draft'} (${business.name || 'Company'})`;

    // 1. Create empty document
    const createRes = await fetch('https://docs.googleapis.com/v1/documents', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ title: docTitle }),
    });

    if (!createRes.ok) {
      const err = await createRes.text();
      throw new Error(`Failed to create Google Doc: ${err}`);
    }

    const docData = await createRes.json();
    const documentId = docData.documentId;

    // 2. Format invoice content in structured text
    const lines: string[] = [];
    lines.push(`TAX INVOICE\n`);
    lines.push(`(Issued under Section 31 of CGST Act, 2017 & Indian GST Rules)\n\n`);

    lines.push(`================================================================================\n`);
    lines.push(`SELLER / SUPPLIER DETAILS:\n`);
    lines.push(`Business Name : ${business.name || 'N/A'}\n`);
    lines.push(`GSTIN         : ${business.gstin || 'Unregistered'}\n`);
    if (business.pan) lines.push(`PAN           : ${business.pan}\n`);
    lines.push(`Address       : ${business.address || ''}, ${business.state || ''} ${business.pincode || ''}\n`);
    lines.push(`State Code    : ${business.stateCode || 'N/A'}\n`);
    if (business.phone) lines.push(`Phone         : ${business.phone}\n`);
    if (business.email) lines.push(`Email         : ${business.email}\n`);
    lines.push(`\n`);

    lines.push(`================================================================================\n`);
    lines.push(`INVOICE DETAILS:\n`);
    lines.push(`Invoice Number: ${invoice.invoiceNumber || 'INV/26-27/1'}\n`);
    lines.push(`Invoice Date  : ${invoice.date || '2026-10-29'}\n`);
    lines.push(`Place of Supply: ${invoice.placeOfSupply || 'Maharashtra'} (State Code: ${invoice.placeOfSupplyCode || '27'})\n`);
    lines.push(`Supply Type   : ${invoice.isInterState ? 'Inter-State (IGST)' : 'Intra-State (CGST + SGST)'}\n`);
    lines.push(`Contract No   : ${invoice.contractNo || 'N/A'}\n`);
    lines.push(`Contract Date : ${invoice.contractDate || 'N/A'}\n`);
    lines.push(`Reverse Charge: ${invoice.reverseCharge ? 'Yes' : 'No'}\n`);
    lines.push(`Payment Status: ${invoice.status}\n`);
    lines.push(`\n`);

    lines.push(`================================================================================\n`);
    lines.push(`BILL TO / RECIPIENT:\n`);
    lines.push(`Customer Name : ${invoice.customerName || 'Cash Customer'}\n`);
    if (invoice.customerGstin) lines.push(`GSTIN         : ${invoice.customerGstin}\n`);
    if (invoice.customerAddress) lines.push(`Address       : ${invoice.customerAddress}\n`);
    if (invoice.customerPhone) lines.push(`Phone         : ${invoice.customerPhone}\n`);
    lines.push(`\n`);

    lines.push(`================================================================================\n`);
    lines.push(`SHIP TO / CONSIGNEE:\n`);
    lines.push(`Consignee Name: ${invoice.shippingName || invoice.customerName || 'Same as Billed To'}\n`);
    lines.push(`Address       : ${invoice.shippingAddress || invoice.customerAddress || 'Same as billing address'}\n`);
    if (invoice.shippingGstin) lines.push(`GSTIN         : ${invoice.shippingGstin}\n`);
    if (invoice.shippingState) lines.push(`Destination   : ${invoice.shippingState} (Code: ${invoice.shippingStateCode || 'N/A'})\n`);
    if (invoice.shippingPhone) lines.push(`Phone         : ${invoice.shippingPhone}\n`);
    lines.push(`\n`);

    lines.push(`================================================================================\n`);
    lines.push(`LINE ITEMS & TAX BREAKDOWN:\n`);
    lines.push(`--------------------------------------------------------------------------------\n`);
    lines.push(`# | Description | HSN | Qty | Unit | Rate (₹) | Discount | Taxable (₹) | GST% | Total (₹)\n`);
    lines.push(`--------------------------------------------------------------------------------\n`);

    invoice.items.forEach((item, idx) => {
      const num = idx + 1;
      const desc = item.name;
      const hsn = item.hsnSac || '-';
      const qty = item.quantity;
      const unit = item.unit || 'PCS';
      const rate = item.unitPrice.toFixed(2);
      const disc = item.discount ? `${item.discount}%` : '0%';
      const taxable = item.taxableAmount.toFixed(2);
      const gstRate = `${item.gstRate}%`;
      const total = item.totalAmount.toFixed(2);
      lines.push(`${num}. ${desc} [HSN: ${hsn}] | Qty: ${qty} ${unit} @ ₹${rate} (Disc: ${disc}) | Taxable: ₹${taxable} | GST: ${gstRate} | Total: ₹${total}\n`);
    });

    lines.push(`--------------------------------------------------------------------------------\n\n`);

    lines.push(`================================================================================\n`);
    lines.push(`FINANCIAL SUMMARY:\n`);
    lines.push(`Taxable Value       : Rs. ${(invoice.totalTaxable || 0).toFixed(2)}\n`);
    if ((invoice.cgstTotal || 0) > 0) lines.push(`CGST                : Rs. ${invoice.cgstTotal.toFixed(2)}\n`);
    if ((invoice.sgstTotal || 0) > 0) lines.push(`SGST                : Rs. ${invoice.sgstTotal.toFixed(2)}\n`);
    if ((invoice.igstTotal || 0) > 0) lines.push(`IGST                : Rs. ${invoice.igstTotal.toFixed(2)}\n`);
    const totalTax = (invoice.cgstTotal || 0) + (invoice.sgstTotal || 0) + (invoice.igstTotal || 0) + (invoice.cessTotal || 0);
    lines.push(`Total GST Tax       : Rs. ${totalTax.toFixed(2)}\n`);
    if (invoice.roundOff !== 0) lines.push(`Round Off           : Rs. ${invoice.roundOff.toFixed(2)}\n`);
    lines.push(`GRAND TOTAL (INR)   : Rs. ${invoice.grandTotal.toFixed(2)}\n`);
    if (invoice.amountInWords) lines.push(`Amount in Words     : ${invoice.amountInWords}\n`);
    lines.push(`Amount Paid         : Rs. ${(invoice.paidAmount || 0).toFixed(2)}\n`);
    lines.push(`Balance Due         : Rs. ${(invoice.balanceDue || 0).toFixed(2)}\n`);
    lines.push(`\n`);

    if (business.accountNumber) {
      lines.push(`================================================================================\n`);
      lines.push(`BANK & PAYMENT DETAILS FOR RTGS / NEFT / IMPS:\n`);
      lines.push(`Bank Name      : ${business.bankName || 'N/A'}\n`);
      lines.push(`Account Name   : ${business.name}\n`);
      lines.push(`Account Number : ${business.accountNumber}\n`);
      lines.push(`IFSC Code      : ${business.ifsc || ''}\n`);
      if (business.branch) lines.push(`Branch         : ${business.branch}\n`);
      if (business.upiId) lines.push(`UPI ID         : ${business.upiId}\n`);
      lines.push(`\n`);
    }

    if (business.termsAndConditions) {
      lines.push(`================================================================================\n`);
      lines.push(`TERMS & CONDITIONS:\n`);
      lines.push(`${business.termsAndConditions}\n\n`);
    }

    lines.push(`Authorized Signatory: ${business.signatureName || business.name}\n`);
    lines.push(`Issued via Zavianoice Official Cloud Suite.\n`);

    const fullContent = lines.join('');

    // 3. Batch update document to insert content
    await fetch(`https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        requests: [
          {
            insertText: {
              location: { index: 1 },
              text: fullContent,
            },
          },
        ],
      }),
    });

    const docUrl = `https://docs.google.com/document/d/${documentId}/edit`;
    return {
      success: true,
      id: documentId,
      url: docUrl,
      title: docTitle,
    };
  } catch (err: any) {
    console.error('createInvoiceGoogleDoc error:', err);
    return {
      success: false,
      error: err.message || 'Failed to create Google Doc',
    };
  }
}

/**
 * Create a formatted Google Doc for a Quotation / Estimate
 */
export async function createQuotationGoogleDoc(
  accessToken: string,
  quotation: Quotation,
  business: Business
): Promise<WorkspaceExportResult> {
  try {
    const docTitle = `Quotation - ${quotation.quoteNumber} (${quotation.customerName})`;

    const createRes = await fetch('https://docs.googleapis.com/v1/documents', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ title: docTitle }),
    });

    if (!createRes.ok) {
      const err = await createRes.text();
      throw new Error(`Failed to create Google Doc: ${err}`);
    }

    const docData = await createRes.json();
    const documentId = docData.documentId;

    const lines: string[] = [];
    lines.push(`FORMAL ESTIMATE / QUOTATION\n\n`);
    lines.push(`Issuer: ${business.name} | GSTIN: ${business.gstin || 'Unregistered'}\n`);
    lines.push(`Quote No: ${quotation.quoteNumber} | Date: ${quotation.date} | Valid Until: ${quotation.validUntil}\n`);
    lines.push(`Recipient: ${quotation.customerName}\n\n`);
    lines.push(`--------------------------------------------------------------------------------\n`);
    lines.push(`ITEMS & SCOPE OF SUPPLY:\n`);
    quotation.items.forEach((item, idx) => {
      lines.push(`${idx + 1}. ${item.name} - Qty: ${item.quantity} @ Rs.${item.unitPrice} (GST: ${item.gstRate}%) = Rs.${item.totalAmount.toFixed(2)}\n`);
    });
    lines.push(`--------------------------------------------------------------------------------\n`);
    lines.push(`Taxable Amount: Rs. ${(quotation.totalTaxable || 0).toFixed(2)}\n`);
    const quoteTax = (quotation.cgstTotal || 0) + (quotation.sgstTotal || 0) + (quotation.igstTotal || 0);
    lines.push(`Total GST: Rs. ${quoteTax.toFixed(2)}\n`);
    lines.push(`GRAND TOTAL: Rs. ${(quotation.grandTotal || 0).toFixed(2)}\n\n`);
    if (quotation.notes) lines.push(`Notes: ${quotation.notes}\n`);
    if (business.termsAndConditions) lines.push(`Terms: ${business.termsAndConditions}\n`);

    await fetch(`https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        requests: [{ insertText: { location: { index: 1 }, text: lines.join('') } }],
      }),
    });

    return {
      success: true,
      id: documentId,
      url: `https://docs.google.com/document/d/${documentId}/edit`,
      title: docTitle,
    };
  } catch (err: any) {
    console.error('createQuotationGoogleDoc error:', err);
    return {
      success: false,
      error: err.message || 'Failed to create quotation Google Doc',
    };
  }
}


/**
 * Export Sales Invoices Register to a styled Google Sheets spreadsheet
 */
export async function exportInvoicesToGoogleSheets(
  accessToken: string,
  invoices: Invoice[],
  business: Business,
  customTitle?: string
): Promise<WorkspaceExportResult> {
  try {
    const dateStr = new Date().toISOString().split('T')[0];
    const sheetTitle = customTitle || `Zavianoice - Sales Register (${dateStr})`;

    const headers = [
      'Invoice No',
      'Invoice Date',
      'Due Date',
      'Customer Name',
      'Customer GSTIN',
      'Place of Supply',
      'Supply Type',
      'Taxable Value (INR)',
      'CGST (INR)',
      'SGST (INR)',
      'IGST (INR)',
      'Total Tax (INR)',
      'Round Off (INR)',
      'Grand Total (INR)',
      'Paid Amount (INR)',
      'Balance Due (INR)',
      'Status',
      'Reverse Charge',
    ];

    const dataRows = invoices.map((inv) => {
      const totTax = (inv.cgstTotal || 0) + (inv.sgstTotal || 0) + (inv.igstTotal || 0) + (inv.cessTotal || 0);
      return [
        inv.invoiceNumber,
        inv.date,
        inv.dueDate || '',
        inv.customerName,
        inv.customerGstin || 'Unregistered',
        inv.placeOfSupply,
        inv.isInterState ? 'Inter-State' : 'Intra-State',
        inv.totalTaxable || 0,
        inv.cgstTotal || 0,
        inv.sgstTotal || 0,
        inv.igstTotal || 0,
        totTax,
        inv.roundOff || 0,
        inv.grandTotal || 0,
        inv.paidAmount || 0,
        inv.balanceDue || 0,
        inv.status,
        inv.reverseCharge ? 'Y' : 'N',
      ];
    });

    const createPayload = {
      properties: {
        title: sheetTitle,
      },
      sheets: [
        {
          properties: {
            title: 'Sales Register',
            gridProperties: {
              frozenRowCount: 1,
            },
          },
          data: [
            {
              startRow: 0,
              startColumn: 0,
              rowData: [
                {
                  values: headers.map((h) => ({
                    userEnteredValue: { stringValue: h },
                    userEnteredFormat: {
                      textFormat: { bold: true },
                      backgroundColor: { red: 0.9, green: 0.93, blue: 0.98 },
                    },
                  })),
                },
                ...dataRows.map((row) => ({
                  values: row.map((cell) => {
                    if (typeof cell === 'number') {
                      return {
                        userEnteredValue: { numberValue: cell },
                        userEnteredFormat: {
                          numberFormat: { type: 'CURRENCY', pattern: '₹#,##0.00' },
                        },
                      };
                    }
                    return {
                      userEnteredValue: { stringValue: String(cell) },
                    };
                  }),
                })),
              ],
            },
          ],
        },
      ],
    };

    const res = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(createPayload),
    });

    if (!res.ok) {
      const err = await res.text();
      throw new Error(`Failed to create Google Sheet: ${err}`);
    }

    const created = await res.json();
    const spreadsheetId = created.spreadsheetId;
    const spreadsheetUrl = `https://sheets.google.com/spreadsheets/d/${spreadsheetId}/edit`;

    return {
      success: true,
      id: spreadsheetId,
      url: spreadsheetUrl,
      title: sheetTitle,
    };
  } catch (err: any) {
    console.error('exportInvoicesToGoogleSheets error:', err);
    return {
      success: false,
      error: err.message || 'Failed to export invoices to Google Sheets',
    };
  }
}


/**
 * Export Products & Inventory Catalog to Google Sheets
 */
export async function exportProductsToGoogleSheets(
  accessToken: string,
  products: Product[],
  title = 'Zavianoice - Products & Inventory Catalog'
): Promise<WorkspaceExportResult> {
  try {
    const headers = [
      'Product ID',
      'Product / Service Name',
      'HSN / SAC Code',
      'Item Type',
      'Unit of Measure',
      'Selling Price (INR)',
      'Purchase Price (INR)',
      'GST Tax Rate (%)',
      'Current Stock',
      'Min Stock Alert Level',
      'Tax Inclusive?',
    ];

    const dataRows = products.map((p) => [
      p.id,
      p.name,
      p.hsnSac || '',
      p.type || 'goods',
      p.unit || 'PCS',
      p.sellingPrice,
      p.purchasePrice || 0,
      p.taxRate,
      p.currentStock || 0,
      p.minStockAlert || 0,
      p.isTaxInclusive ? 'Yes' : 'No',
    ]);

    const createPayload = {
      properties: { title },
      sheets: [
        {
          properties: {
            title: 'Products Inventory',
            gridProperties: { frozenRowCount: 1 },
          },
          data: [
            {
              startRow: 0,
              startColumn: 0,
              rowData: [
                {
                  values: headers.map((h) => ({
                    userEnteredValue: { stringValue: h },
                    userEnteredFormat: {
                      textFormat: { bold: true },
                      backgroundColor: { red: 0.98, green: 0.94, blue: 0.9 },
                    },
                  })),
                },
                ...dataRows.map((row) => ({
                  values: row.map((cell) => {
                    if (typeof cell === 'number') {
                      return {
                        userEnteredValue: { numberValue: cell },
                      };
                    }
                    return {
                      userEnteredValue: { stringValue: String(cell) },
                    };
                  }),
                })),
              ],
            },
          ],
        },
      ],
    };

    const res = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(createPayload),
    });

    if (!res.ok) {
      const err = await res.text();
      throw new Error(`Failed to create Google Sheet: ${err}`);
    }

    const created = await res.json();
    return {
      success: true,
      id: created.spreadsheetId,
      url: `https://sheets.google.com/spreadsheets/d/${created.spreadsheetId}/edit`,
      title,
    };
  } catch (err: any) {
    console.error('exportProductsToGoogleSheets error:', err);
    return {
      success: false,
      error: err.message || 'Failed to export products to Google Sheets',
    };
  }
}
